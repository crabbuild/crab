    /// The JSON payload mirrors the graph: stages in topo order,
    /// edges sorted by (from, to), both deterministic across runs.
    #[test]
    fn payload_stage_and_edge_ordering_is_deterministic() {
        let wf = make_workflow(vec![
            make_stage("a", Vec::new(), vec![file_out("a.out")]),
            make_stage("b", vec![path_dep("a.out")], vec![file_out("b.out")]),
            make_stage("c", vec![path_dep("a.out")], vec![file_out("c.out")]),
            make_stage("d", vec![path_dep("b.out"), path_dep("c.out")], Vec::new()),
        ]);
        let graph = Graph::build(&wf.stages).unwrap();
        let view = stage_view(&graph, &wf);
        let payload = build_payload(&view);
        let stage_names: Vec<&str> = payload.stages.iter().map(|s| s.name.as_str()).collect();
        assert_eq!(stage_names, vec!["a", "b", "c", "d"]);
        let edges: Vec<(&str, &str)> = payload
            .edges
            .iter()
            .map(|e| (e.from.as_str(), e.to.as_str()))
            .collect();
        assert_eq!(edges, vec![("a", "b"), ("a", "c"), ("b", "d"), ("c", "d")]);
        // All stages default to cpu=1, gpu=0, memory=0.
        for stage in &payload.stages {
            assert_eq!(stage.resources.cpu, 1);
            assert_eq!(stage.resources.gpu, 0);
            assert_eq!(stage.resources.memory_bytes, 0);
            assert!(!stage.expanded, "non-expanded stage marked expanded");
        }
    }

