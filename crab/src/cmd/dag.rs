    /// Expanded stages (from foreach/matrix) appear as individual
    /// nodes in the DAG with an `[expanded]` annotation in ASCII
    /// output and proper Mermaid node IDs with `@` escaped.
    #[test]
    fn expanded_stages_appear_as_individual_nodes() {
        let wf = make_workflow(vec![
            make_stage(
                "ingest",
                Vec::new(),
                vec![file_out("raw_a.csv"), file_out("raw_b.csv")],
            ),
            make_stage(
                "preprocess@raw_a",
                vec![path_dep("raw_a.csv")],
                vec![file_out("clean_a.csv")],
            ),
            make_stage(
                "preprocess@raw_b",
                vec![path_dep("raw_b.csv")],
                vec![file_out("clean_b.csv")],
            ),
            make_stage(
                "train",
                vec![path_dep("clean_a.csv"), path_dep("clean_b.csv")],
                Vec::new(),
            ),
        ]);
        let graph = Graph::build(&wf.stages).unwrap();
        let view = stage_view(&graph, &wf);

        // ASCII: expanded stages carry the [expanded] annotation.
        let ascii = render_ascii(&view);
        assert!(
            ascii.contains("preprocess@raw_a [expanded]\n"),
            "expanded annotation missing for preprocess@raw_a:\n{ascii}"
        );
        assert!(
            ascii.contains("preprocess@raw_b [expanded]\n"),
            "expanded annotation missing for preprocess@raw_b:\n{ascii}"
        );
        // Non-expanded stages do NOT carry the annotation.
        assert!(
            ascii.contains("ingest\n"),
            "ingest should not have [expanded]:\n{ascii}"
        );
        assert!(
            ascii.contains("train\n"),
            "train should not have [expanded]:\n{ascii}"
        );

        // Mermaid: internal node IDs stay simple while labels preserve `@`.
        let mermaid = render_mermaid(&view);
        assert!(
            mermaid.contains("[\"preprocess@raw_a\"]"),
            "expanded stage label missing:\n{mermaid}"
        );
        assert!(
            mermaid.contains("[\"preprocess@raw_b\"]"),
            "expanded stage label missing:\n{mermaid}"
        );
        // Edges use the generated node IDs in topological node order.
        assert!(
            mermaid.contains("node1 --> node2"),
            "edge to expanded stage missing:\n{mermaid}"
        );
        assert!(
            mermaid.contains("node1 --> node3"),
            "edge to expanded stage missing:\n{mermaid}"
        );
        assert!(
            mermaid.contains("node2 --> node4"),
            "edge from expanded stage missing:\n{mermaid}"
        );
        assert!(
            mermaid.contains("node3 --> node4"),
            "edge from expanded stage missing:\n{mermaid}"
        );
    }

