//! `crab workflow dag` — visualize the workflow DAG.
//!
//! Parses `crab.yaml` (respecting `[workflow] discover` / `--recursive`
//! per R2), builds a [`Graph`][crab_workflow::Graph], and
//! renders the topological structure in one of two formats:
//!
//! - **ASCII**: one line per stage in topological order. Each line
//!   starts with the stage name and lists incoming deps below it
//!   prefixed with `├─ dep_name`. Source stages (no producers) show
//!   `└─ (no deps)` so the reader can distinguish "no upstream" from
//!   "we forgot to print something".
//! - **Mermaid**: a `graph TD` block with one node per stage and one
//!   edge per producer → consumer relation. Output is ready to paste
//!   into any Markdown reader that renders Mermaid.
//!
//! `--json` emits a structured `workflow.dag` envelope listing every
//! stage and every inferred edge, so tools downstream of the CLI
//! (CI dashboards, static-analysis bots) can consume the DAG without
//! reparsing yaml.
//!
//! The command is pure-read — it doesn't open the journal, doesn't
//! touch the cache, doesn't acquire the scheduler lock. Safe to run
//! mid-execution of another `crab run`.

