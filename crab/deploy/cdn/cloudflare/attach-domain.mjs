import { readFile } from "node:fs/promises";
import { join } from "node:path";

async function main() {
  const [directory] = process.argv.slice(2);
  if (process.argv.length !== 3) throw new Error("Usage: node attach-domain.mjs DIRECTORY");
  const token = process.env.CLOUDFLARE_API_TOKEN;
  if (!token) throw new Error("Set CLOUDFLARE_API_TOKEN before attaching the hostname");

  const config = JSON.parse(await readFile(join(directory, "wrangler.json"), "utf8"));
  const { account_id: account, name: worker, vars, workers_dev: development, preview_urls: previews } = config;
  const hostname = vars?.CRAB_VIEWER_HOST;
  if (!/^[a-f0-9]{32}$/.test(account) || !/^crab-r2-[a-f0-9]{24}$/.test(worker)
      || typeof hostname !== "string" || !hostname || development !== false || previews !== false) {
    throw new Error("Use a private deployment generated by setup.mjs");
  }

  const url = new URL(`https://api.cloudflare.com/client/v4/accounts/${account}/workers/domains`);
  async function request(endpoint, options) {
    const response = await fetch(endpoint, {
      ...options,
      redirect: "error",
      signal: AbortSignal.timeout(30_000),
      headers: { Authorization: `Bearer ${token}`, "Content-Type": "application/json" },
    });
    const body = await response.json().catch(() => null);
    if (!response.ok || !body?.success) {
      const codes = (body?.errors ?? []).map(({ code }) => code).filter(Number.isInteger);
      throw new Error(`Cloudflare Worker Domains API returned HTTP ${response.status}${codes.length ? ` (${codes.join(", ")})` : ""}`);
    }
    return body.result;
  }

  const query = new URL(url);
  query.searchParams.set("hostname", hostname);
  const domains = await request(query);
  const bindings = domains.filter((domain) => domain.hostname === hostname);
  if (bindings.length > 1 || bindings.some((domain) => domain.service !== worker)) {
    throw new Error(`Choose an unused hostname; ${hostname} has another Worker binding`);
  }
  if (bindings[0]?.enabled === true && bindings[0]?.previews_enabled === false) {
    console.log(`${hostname} is already attached to ${worker}`);
    return;
  }
  const attached = await request(url, {
    method: "PUT",
    body: JSON.stringify({ hostname, service: worker, enabled: true, previews_enabled: false }),
  });
  if (attached.hostname !== hostname || attached.service !== worker
      || attached.enabled !== true || attached.previews_enabled !== false) {
    throw new Error("Cloudflare did not confirm the requested private hostname");
  }
  console.log(`Attached ${hostname} to ${worker}`);
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
