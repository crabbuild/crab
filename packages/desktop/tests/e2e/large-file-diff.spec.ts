import { test, expect, _electron as electron } from "@playwright/test";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } from "node:fs";
import * as path from "node:path";
import { tmpdir } from "node:os";
import { call, packagedExecutable } from "./packaged-app";
import type { ChunkDiffMetrics } from "../../src/ipc";

test("packaged desktop compares actual Crab chunks and LFS identities across versions", async () => {
  test.setTimeout(180_000);
  const executablePath = packagedExecutable();
  const resources = process.platform === "darwin" ? path.resolve(path.dirname(executablePath), "../Resources") : path.join(path.dirname(executablePath), "resources");
  const crab = path.join(resources, "agent", process.platform === "win32" ? "crab.exe" : "crab");
  const root = mkdtempSync(path.join(process.env.CARGO_TARGET_DIR ?? tmpdir(), "desktop-file-diff-"));
  const source = path.join(root, "source");
  mkdirSync(source);
  writeFileSync(path.join(root, "gitconfig"), "");
  const env: NodeJS.ProcessEnv = { ...process.env, CRAB_CACHE_DIR: path.join(root, "cache"), GIT_CONFIG_GLOBAL: path.join(root, "gitconfig"), GIT_CONFIG_NOSYSTEM: "1" };
  delete env.GIT_DIR; delete env.GIT_WORK_TREE; delete env.GIT_INDEX_FILE;
  const git = (args: string[]) => execFileSync("git", args, { cwd: source, env });
  let application: Awaited<ReturnType<typeof electron.launch>> | undefined;
  try {
    git(["init", "--initial-branch=main"]);
    git(["config", "user.name", "Desktop test"]);
    git(["config", "user.email", "test@example.invalid"]);
    const driver = `'${crab.replaceAll("\\", "/").replaceAll("'", "'\\''")}' filter-process`;
    git(["config", "filter.crab.process", driver]);
    git(["config", "filter.crab.required", "true"]);
    writeFileSync(path.join(source, ".gitignore"), ".crab/\n");
    writeFileSync(path.join(source, ".gitattributes"), "dataset.bin filter=crab -text\n");
    const content = Buffer.alloc(64 * 1024 ** 2);
    content.write("retained");
    const lfs = (text: string) => `version https://git-lfs.github.com/spec/v1\noid sha256:${createHash("sha256").update(text).digest("hex")}\nsize ${Buffer.byteLength(text)}\n`;
    writeFileSync(path.join(source, "dataset.bin"), content);
    writeFileSync(path.join(source, "lfs.bin"), lfs("before"));
    writeFileSync(path.join(source, "ordinary.txt"), "Docs: crab.dev/v1 and https://git-lfs.github.com/spec/v1\nBinary files a/x and b/x differ\nbefore\n");
    git(["add", ".gitignore", ".gitattributes", "dataset.bin", "lfs.bin", "ordinary.txt"]);
    git(["-c", "commit.gpgsign=false", "commit", "-m", "Diff fixture"]);
    for (let offset = 1024 ** 2; offset < content.length - 1024 ** 2; offset += 1024 ** 2) content[offset] = 1;
    writeFileSync(path.join(source, "dataset.bin"), content);
    git(["add", "dataset.bin"]);
    const stagedPointer = git(["show", ":dataset.bin"]);
    content[content.length - 10] = 2;
    writeFileSync(path.join(source, "dataset.bin"), content);
    writeFileSync(path.join(source, "lfs.bin"), lfs("after!"));
    writeFileSync(path.join(source, "ordinary.txt"), "Docs: crab.dev/v1 and https://git-lfs.github.com/spec/v1\nBinary files a/x and b/x differ\nafter\n");
    application = await electron.launch({ executablePath, env, args: [`--user-data-dir=${path.join(root, "profile")}`] });
    const page = await application.firstWindow();
    page.on("pageerror", error => console.error("Renderer error:", error.message));
    await page.getByRole("button", { name: "Skip", exact: true }).click();
    await page.getByRole("button", { name: "No thanks", exact: true }).click();
    await expect.poll(async () => { try { return (await call(page, "ping", {})).pong; } catch { return undefined; } }).toBeTruthy();
    const handle = await call(page, "open_local", { repo_id: "file-diff", path: source });
    await page.evaluate(({ handle, source }) => window.dispatchEvent(new CustomEvent("crab:repo-opened", { detail: { handle, path: source } })), { handle, source });
    const native = await call(page, "file_diff", { repo_id: "file-diff", path: "dataset.bin", before: { kind: "revision", rev: "HEAD" }, after: { kind: "index" } });
    const metrics = native.chunk_metrics as ChunkDiffMetrics;
    expect(native.status).toBe("modified");
    expect(metrics.signed_delta_bytes).toBe(0);
    expect(metrics.added_bytes).toBeGreaterThan(0);
    expect(metrics.unchanged_bytes).toBeGreaterThan(0);
    expect(metrics.changed_byte_ranges_new.length).toBeGreaterThan(50);
    await test.info().attach("native-metrics", { body: JSON.stringify(metrics), contentType: "application/json" });
    const primary = page.getByRole("navigation", { name: "Primary", exact: true });
    const openDiff = async (file: string) => {
      await primary.getByRole("button", { name: "Git", exact: true }).click();
      await page.getByRole("navigation", { name: "Git", exact: true }).getByRole("button", { name: "Changes", exact: true }).click();
      await page.getByRole("radio", { name: "List", exact: true }).click();
      await page.getByRole("listbox", { name: "Changed files", exact: true }).getByRole("option").filter({ hasText: file }).dblclick();
    };
    await openDiff("dataset.bin");
    const selector = page.getByRole("combobox", { name: "Compare file versions", exact: true });
    await selector.selectOption("staged");
    const comparison = page.getByTestId("large-file-diff");
    await expect(comparison.getByText("modified", { exact: true })).toBeVisible();
    await expect(comparison.getByText("0 B", { exact: true })).toBeVisible();
    const ranges = comparison.getByRole("region", { name: "Changed ranges after", exact: true });
    await expect(ranges.locator("tbody tr")).toHaveCount(50);
    const firstOffset = await ranges.locator("tbody tr").first().getByRole("cell").first().innerText();
    await page.screenshot({ path: test.info().outputPath("crab-chunk-summary.png") });
    await ranges.getByRole("button", { name: "Next ranges", exact: true }).click();
    await expect(ranges.locator("tbody tr").first().getByRole("cell").first()).not.toHaveText(firstOffset);
    await page.screenshot({ path: test.info().outputPath("crab-staged-chunk-diff.png") });
    await selector.selectOption("unstaged");
    await expect(comparison.getByText(/staged.*worktree/)).toBeVisible();
    await openDiff("lfs.bin");
    await expect(comparison.getByText("modified", { exact: true })).toBeVisible();
    await expect(comparison.getByText(/no shared Crab chunk recipe/)).toBeVisible();
    await expect(comparison.getByText("0 B", { exact: true })).toBeVisible();
    await page.screenshot({ path: test.info().outputPath("lfs-same-size-content-diff.png") });
    await openDiff("ordinary.txt");
    await expect(comparison).toHaveCount(0);
    await expect(page.locator("diffs-container").getByText("after", { exact: true }).first()).toBeVisible();
    const unchanged = await call(page, "file_diff", { repo_id: "file-diff", path: "ordinary.txt", before: { kind: "revision", rev: "HEAD" }, after: { kind: "revision", rev: "HEAD" } });
    expect(unchanged).toEqual({ kind: "git", path: "ordinary.txt", patch: "" });
    await primary.getByRole("button", { name: "Git", exact: true }).click();
    await page.getByRole("navigation", { name: "Git", exact: true }).getByRole("button", { name: "History", exact: true }).click();
    await page.getByRole("listbox", { name: "Commits", exact: true }).getByText("Diff fixture", { exact: true }).click();
    await page.getByTestId("large-file-diff").first().scrollIntoViewIfNeeded();
    await expect(page.getByTestId("large-file-diff").first().getByText("added", { exact: true })).toBeVisible();
    await page.screenshot({ path: test.info().outputPath("initial-commit-large-file-diff.png") });
    expect(git(["show", ":dataset.bin"]).equals(stagedPointer)).toBe(true);
    expect(readFileSync(path.join(source, "dataset.bin")).equals(content)).toBe(true);
  } catch (error) {
    const page = application?.windows()[0];
    if (page) {
      await page.screenshot({ path: test.info().outputPath("failure.png"), timeout: 2000 }).catch(() => undefined);
      await page.locator("body").innerText({ timeout: 2000 }).then(body => test.info().attach("failure-state", { body, contentType: "text/plain" })).catch(() => undefined);
    }
    throw error;
  } finally {
    await application?.close();
    rmSync(root, { recursive: true, force: true });
  }
});
