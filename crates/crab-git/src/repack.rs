/// A downloaded canonical pack selected by a pinned repository manifest.
#[derive(Debug, Clone)]
pub struct RepackSource {
    /// Blake3 content identifier used by the canonical repository inventory.
    pub canonical_id: String,
    /// Local path containing the complete pack body.
    pub path: PathBuf,
    /// Local path containing the committed Git pack index.
    pub index_path: PathBuf,
    /// Local path containing the committed Git reverse index.
    pub reverse_index_path: PathBuf,
    /// Size committed by the source manifest.
    pub size: u64,
    /// Object count committed by the source manifest.
    pub object_count: u64,
    /// Identity verified while the source pack was streamed, when available.
    ///
    /// This lets the response producer avoid hashing the same immutable pack
    /// body again while installing its already-verified sidecars.
    pub verified_identity: Option<VerifiedPackIdentity>,
}

/// One verified object required to resolve a selected pack's REF_DELTA entry.
#[derive(Debug, Clone)]
pub struct RepackDeltaBase {
    /// Git object ID bound to `kind` and `data`.
    pub oid: gix_hash::ObjectId,
    /// Canonical Git object kind.
    pub kind: gix_object::Kind,
    /// Uncompressed object payload without the Git object header.
    pub data: Vec<u8>,
}

/// One authorized annotated tag considered for shallow fetch inclusion.
#[derive(Debug, Clone, Copy)]
pub struct ShallowFetchTag {
    /// Annotated tag object referenced by the visible tag ref.
    pub target: gix_hash::ObjectId,
    /// Final object referenced by the annotated tag chain.
    pub peeled: gix_hash::ObjectId,
}

/// A verified pack produced by geometric consolidation.
#[derive(Debug)]
pub struct GeometricRepackedPack {
    pack_path: PathBuf,
    index_path: PathBuf,
    reverse_index_path: PathBuf,
    /// Blake3 content identifier of the pack.
    pub pack_id: String,
    /// Raw Blake3 digest used by multipart integrity verification.
    pub pack_hash: [u8; 32],
    /// Pack size.
    pub pack_size: u64,
    /// Raw Blake3 digest of the Git index.
    pub index_hash: [u8; 32],
    /// Git index size.
    pub index_size: u64,
    /// Raw Blake3 digest of the reverse index.
    pub reverse_index_hash: [u8; 32],
    /// Git reverse-index size.
    pub reverse_index_size: u64,
    /// Number of objects in the pack.
    pub object_count: u64,
    /// Git-native SHA-1 checksum of the pack.
    pub git_sha1: String,
    /// Whether the pack body was newly generated by geometric repack.
    pub is_new: bool,
}

impl GeometricRepackedPack {
    /// Returns the verified pack path.
    #[must_use]
    pub fn pack_path(&self) -> &Path {
        &self.pack_path
    }

    /// Returns the verified Git index path.
    #[must_use]
    pub fn index_path(&self) -> &Path {
        &self.index_path
    }

    /// Returns the verified Git reverse-index path.
    #[must_use]
    pub fn reverse_index_path(&self) -> &Path {
        &self.reverse_index_path
    }
}

