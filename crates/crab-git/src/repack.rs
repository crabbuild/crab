/// Errors raised while consolidating a complete Git object database.
#[derive(Debug, thiserror::Error)]
#[non_exhaustive]
pub enum RepackError {
    /// Filesystem work failed.
    #[error("{context}: {source}")]
    Io {
        context: String,
        #[source]
        source: io::Error,
    },
    /// A source pack failed Git pack validation.
    #[error(transparent)]
    Pack {
        #[from]
        source: PackError,
    },
    /// A generated or installed pack index failed locator validation.
    #[error(transparent)]
    Locator {
        #[from]
        source: PackLocatorError,
    },
    /// A source pack no longer matches its manifest commitment.
    #[error("source pack {pack_id} failed its manifest commitment: {reason}")]
    SourceIntegrity { pack_id: String, reason: String },
    /// Repacking an inventory without refs cannot prove repository reachability.
    #[error("cannot repack a repository without refs")]
    EmptyRefs,
    /// A Git subprocess rejected the source or replacement repository.
    #[error("{operation} failed with {status}")]
    Git {
        operation: &'static str,
        status: std::process::ExitStatus,
    },
    /// A selected-object pack contained an object outside the requested set.
    #[error("selected pack {pack_id} failed exact object-set validation: {reason}")]
    SelectedObjectSet { pack_id: String, reason: String },
}

#[derive(Clone, Copy)]
enum GeneratedPackValidation {
    Structural,
    Full,
}

/// Return the number of smallest packs that must be rolled up for geometry.
///
/// Counts are interpreted by object count, matching `git repack
/// --geometric`. Zero means the inventory already satisfies the invariant.
#[must_use]
pub fn geometric_repack_cut(object_counts: &[u64], factor: u64) -> usize {
    if factor < 2 || object_counts.len() < 2 {
        return 0;
    }
    let mut counts = object_counts.to_vec();
    counts.sort_unstable_by(|left, right| right.cmp(left));
    if counts
        .windows(2)
        .all(|pair| pair[0] >= pair[1].saturating_mul(factor))
    {
        return 0;
    }
    let prefix_is_geometric = |end: usize| {
        counts[..end]
            .windows(2)
            .all(|pair| pair[0] >= pair[1].saturating_mul(factor))
    };
    let mut rolled_objects = counts[counts.len() - 1];
    for cut in (1..counts.len()).rev() {
        if prefix_is_geometric(cut) && counts[cut - 1] >= rolled_objects.saturating_mul(factor) {
            return counts.len() - cut;
        }
        rolled_objects = rolled_objects.saturating_add(counts[cut - 1]);
    }
    counts.len()
}

/// Return the smallest suffix worth coalescing during background maintenance.
///
/// `weights` are sorted internally in descending order, normally using
/// verified compressed pack bytes. The smallest tier is promoted only after it
/// has accumulated enough weight to be comparable with its next tier, and the
/// largest pack is left untouched whenever a lower-tier promotion is possible.
/// Every lower tier is inspected, so a stable tiny tail cannot hide a collision
/// between larger packs accumulated since the previous maintenance pass.
/// Two packs are consolidated only when the smaller pack has reached the next
/// tier; a tiny tail must not rewrite the repository-sized pack.
#[must_use]
pub fn incremental_repack_cut(weights: &[u64], factor: u64) -> usize {
    if factor < 2 || weights.len() < 2 {
        return 0;
    }
    let mut weights = weights.to_vec();
    weights.sort_unstable_by(|left, right| right.cmp(left));

    if weights.len() == 2 {
        return if weights[1].saturating_mul(factor) > weights[0] {
            2
        } else {
            0
        };
    }

    let Some(mut start) = (1..weights.len() - 1)
        .find(|index| weights[*index] < weights[*index + 1].saturating_mul(factor))
    else {
        return 0;
    };
    let mut selected_weight = weights[start..]
        .iter()
        .copied()
        .fold(0_u64, u64::saturating_add);
    while start > 1 && selected_weight.saturating_mul(factor) > weights[start - 1] {
        start -= 1;
        selected_weight = selected_weight.saturating_add(weights[start]);
    }
    weights.len() - start
}

/// Consolidates source packs using Git's geometric pack policy.
pub fn repack_repository_geometric(
    sources: &[RepackSource],
    refs: &BTreeSet<String>,
) -> Result<GeometricRepackedRepository, RepackError> {
    if refs.is_empty() {
        return Err(RepackError::EmptyRefs);
    }
    let workspace =
        tempfile::tempdir().map_err(|source| io_error("create repack workspace", source))?;
    let source_git = workspace.path().join("source.git");
    initialize_bare_repository(&source_git)?;
    let pack_dir = source_git.join("objects/pack");
    let concurrency = std::thread::available_parallelism()
        .map_or(DEFAULT_REPACK_INDEX_CONCURRENCY, |parallelism| {
            parallelism.get().min(DEFAULT_REPACK_INDEX_CONCURRENCY)
        });
    let _ = install_source_packs(&pack_dir, sources, concurrency, false)?;
    pin_refs_and_fsck(&source_git, refs, "validate source repository")?;
    run_git(
        Command::new("git")
            .arg(format!("--git-dir={}", source_git.display()))
            .arg("repack")
            .arg("-q")
            .arg("-d")
            .arg("-g")
            .arg("2")
            .arg("--depth=64"),
        "geometrically repack source repository",
    )?;

    let source_ids = sources
        .iter()
        .map(|source| source.canonical_id.as_str())
        .collect::<BTreeSet<_>>();
    let mut pack_paths = Vec::new();
    for entry in std::fs::read_dir(&pack_dir)
        .map_err(|source| io_error(format!("read {}", pack_dir.display()), source))?
    {
        let path = entry
            .map_err(|source| io_error(format!("read entry in {}", pack_dir.display()), source))?
            .path();
        if path
            .extension()
            .is_some_and(|extension| extension == "pack")
        {
            pack_paths.push(path);
        }
    }
    pack_paths.sort_unstable();
    if pack_paths.is_empty() {
        return Err(RepackError::SourceIntegrity {
            pack_id: "geometric-repack".to_owned(),
            reason: "geometric repack produced no pack files".to_owned(),
        });
    }

    let mut packs = Vec::with_capacity(pack_paths.len());
    for pack_path in pack_paths {
        let index_path = pack_path.with_extension("idx");
        let reverse_index_path = pack_path.with_extension("rev");
        if !reverse_index_path.is_file() {
            write_pack_reverse_index(&index_path, &reverse_index_path)?;
        }
        if !index_path.is_file() || !reverse_index_path.is_file() {
            return Err(RepackError::SourceIntegrity {
                pack_id: pack_path.display().to_string(),
                reason: "geometric repack did not produce complete pack indexes".to_owned(),
            });
        }
        let pack_size = std::fs::metadata(&pack_path)
            .map_err(|source| io_error(format!("stat {}", pack_path.display()), source))?
            .len();
        let locations = PackLocationIter::open(&index_path, &reverse_index_path, pack_size)?;
        let object_count = locations.object_count();
        let git_sha1 = locations.pack_checksum().to_string();
        run_git(
            Command::new("git")
                .arg("verify-pack")
                .arg("-v")
                .arg(&index_path)
                .stdout(Stdio::null()),
            "verify geometrically repacked pack",
        )?;
        let (pack_hash, hashed_pack_size) = hash_file(&pack_path)?;
        if hashed_pack_size != pack_size {
            return Err(RepackError::SourceIntegrity {
                pack_id: pack_path.display().to_string(),
                reason: "pack changed during geometric validation".to_owned(),
            });
        }
        let pack_id = blake3::Hash::from_bytes(pack_hash).to_hex().to_string();
        let (index_hash, index_size) = hash_file(&index_path)?;
        let (reverse_index_hash, reverse_index_size) = hash_file(&reverse_index_path)?;
        packs.push(GeometricRepackedPack {
            pack_path,
            index_path,
            reverse_index_path,
            pack_id: pack_id.clone(),
            pack_hash,
            pack_size,
            index_hash,
            index_size,
            reverse_index_hash,
            reverse_index_size,
            object_count,
            git_sha1,
            is_new: !source_ids.contains(pack_id.as_str()),
        });
    }

    let replacement_paths = packs
        .iter()
        .map(|pack| {
            (
                pack.pack_path.as_path(),
                pack.index_path.as_path(),
                pack.reverse_index_path.as_path(),
            )
        })
        .collect::<Vec<_>>();
    validate_replacement_packs(workspace.path(), refs, &replacement_paths)?;
    Ok(GeometricRepackedRepository {
        _workspace: workspace,
        packs,
    })
}

/// Consolidate exactly the supplied packs while preserving their object set.
///
/// This is the object-store maintenance primitive: callers select the
/// geometric roll-up suffix and leave stable large packs remote. Installed Git
/// packs are self-contained, so Git can consume their verified pack basenames
/// directly without downloading or serializing an additional OID list. The
/// generated pack is still compared with the source object universe before it
/// leaves this function.
pub fn consolidate_pack_suffix(
    sources: &[RepackSource],
) -> Result<GeometricRepackedRepository, RepackError> {
    let concurrency = std::thread::available_parallelism()
        .map_or(DEFAULT_REPACK_INDEX_CONCURRENCY, |parallelism| {
            parallelism.get().min(DEFAULT_REPACK_INDEX_CONCURRENCY)
        });
    consolidate_pack_suffix_with_options(sources, &[], concurrency, ConsolidationValidation::Full)
}

/// Consolidate immutable source packs for a generated response pack.
///
/// Source packs must already have passed the publication-time object check,
/// and callers must compare the generated pack with their exact response
/// selection. This path retains pack/index integrity validation while avoiding
/// a second full object-graph scan that the response exact-set check supersedes.
pub fn consolidate_pack_suffix_for_response(
    sources: &[RepackSource],
) -> Result<GeometricRepackedRepository, RepackError> {
    let concurrency = std::thread::available_parallelism()
        .map_or(DEFAULT_REPACK_INDEX_CONCURRENCY, |parallelism| {
            parallelism.get().min(DEFAULT_REPACK_INDEX_CONCURRENCY)
        });
    consolidate_pack_suffix_with_options(
        sources,
        &[],
        concurrency,
        ConsolidationValidation::Response,
    )
}

/// Consolidate selected packs with bounded local index parallelism.
///
/// A zero `index_concurrency` value is treated as one. The source bodies are
/// independent files, so indexing them concurrently shortens the local
/// installation phase without changing the order used by Git pack-objects.
pub fn consolidate_pack_suffix_with_concurrency(
    sources: &[RepackSource],
    index_concurrency: usize,
) -> Result<GeometricRepackedRepository, RepackError> {
    consolidate_pack_suffix_with_options(
        sources,
        &[],
        index_concurrency,
        ConsolidationValidation::Full,
    )
}

/// Consolidate canonical packs already admitted by Crab publication.
///
/// The immutable body identity and committed index pair are revalidated, but
/// object inflation is not repeated. Publication must have quarantined and
/// hash-verified every object before placing the pack in the manifest.
pub fn consolidate_committed_pack_suffix_with_concurrency(
    sources: &[RepackSource],
    index_concurrency: usize,
) -> Result<GeometricRepackedRepository, RepackError> {
    consolidate_committed_pack_suffix_with_delta_bases(sources, &[], index_concurrency)
}

/// Consolidate committed packs with verified REF_DELTA bases.
///
/// Bases are installed only as temporary loose objects. They make thin-pack
/// repair independent of selected-pack order but are not added to the selected
/// object universe or replacement unless already present in `sources`.
pub fn consolidate_committed_pack_suffix_with_delta_bases(
    sources: &[RepackSource],
    delta_bases: &[RepackDeltaBase],
    index_concurrency: usize,
) -> Result<GeometricRepackedRepository, RepackError> {
    consolidate_pack_suffix_with_options(
        sources,
        delta_bases,
        index_concurrency,
        ConsolidationValidation::Committed,
    )
}

#[derive(Clone, Copy)]
enum ConsolidationValidation {
    Full,
    Committed,
    Response,
}

fn consolidate_pack_suffix_with_options(
    sources: &[RepackSource],
    delta_bases: &[RepackDeltaBase],
    index_concurrency: usize,
    validation: ConsolidationValidation,
) -> Result<GeometricRepackedRepository, RepackError> {
    if sources.len() < 2 {
        return Err(RepackError::SourceIntegrity {
            pack_id: "geometric-repack".to_owned(),
            reason: "geometric consolidation requires at least two source packs".to_owned(),
        });
    }
    let mut source_ids = BTreeSet::new();
    for source in sources {
        if !source_ids.insert(source.canonical_id.as_str()) {
            return Err(RepackError::SourceIntegrity {
                pack_id: source.canonical_id.clone(),
                reason: "duplicate source pack id".to_owned(),
            });
        }
    }
    let workspace =
        tempfile::tempdir().map_err(|source| io_error("create repack workspace", source))?;
    let source_git = workspace.path().join("source.git");
    initialize_bare_repository(&source_git)?;
    let pack_dir = source_git.join("objects/pack");
    let install_started = Instant::now();
    let collect_source_oids = matches!(
        validation,
        ConsolidationValidation::Full | ConsolidationValidation::Committed
    );
    let (mut source_oids, source_indexes) =
        install_source_packs(&pack_dir, sources, index_concurrency, collect_source_oids)?;
    tracing::debug!(
        source_pack_count = sources.len(),
        index_concurrency = index_concurrency.max(1).min(sources.len()),
        elapsed_ms = install_started.elapsed().as_millis() as u64,
        "installed source packs for consolidation"
    );
    let source_objects_are_disjoint = if collect_source_oids {
        // Selected suffixes may reference stable packs outside this operation;
        // validate each selected pack's own body and index without requiring a
        // complete repository graph.
        if matches!(validation, ConsolidationValidation::Full) {
            let verify_started = Instant::now();
            for index_batch in source_indexes.chunks(MAX_VERIFY_PACKS_PER_COMMAND) {
                let mut verify = Command::new("git");
                verify
                    .arg("verify-pack")
                    .arg("--")
                    .args(index_batch)
                    .stdout(Stdio::null());
                run_git(&mut verify, "verify consolidated source packs")?;
            }
            tracing::debug!(
                source_pack_count = source_indexes.len(),
                elapsed_ms = verify_started.elapsed().as_millis() as u64,
                "verified consolidated source packs"
            );
        }
        source_oids.sort_unstable();
        let disjoint = !source_oids.windows(2).any(|pair| pair[0] == pair[1]);
        source_oids.dedup();
        disjoint
    } else {
        false
    };

    // Complete packs with disjoint object sets can be joined without Git's
    // expensive delta search. OFS_DELTA distances and entry CRCs remain valid
    // when an entire source body moves by one constant offset. The source-body
    // verification above plus the rebuilt index and exact OID comparison prove
    // the replacement object universe without reinflating every growing tree.
    if source_objects_are_disjoint {
        let expected_oids = source_oids
            .iter()
            .copied()
            .map(gix_hash::ObjectId::from)
            .collect::<Vec<_>>();
        let concatenated = concatenate_complete_pack_inventory_inner(sources, false)?;
        let pack_path = pack_dir.join("pack-crab-rollup-concatenated.pack");
        std::fs::copy(concatenated.pack_path(), &pack_path)
            .map_err(|source| io_error(format!("copy {}", pack_path.display()), source))?;
        let index_path = pack_path.with_extension("idx");
        let index_started = Instant::now();
        let pack_checksum = gix_hash::ObjectId::from_hex(concatenated.git_sha1.as_bytes())
            .map_err(|error| RepackError::SourceIntegrity {
                pack_id: concatenated.pack_id.clone(),
                reason: format!("concatenated pack has an invalid SHA-1 checksum: {error}"),
            })?;
        write_concatenated_pack_index(sources, &index_path, pack_checksum)?;
        tracing::debug!(
            source_pack_count = sources.len(),
            elapsed_ms = index_started.elapsed().as_millis() as u64,
            "concatenated disjoint Git packs"
        );
        let generated = verified_generated_pack(
            pack_path,
            GeneratedPackValidation::Structural,
            Some(&expected_oids),
            None,
        )?;
        return Ok(GeometricRepackedRepository {
            _workspace: workspace,
            packs: vec![generated],
        });
    }

    let pack_generation_started = Instant::now();
    let generated_pack_dir = if delta_bases.is_empty() {
        let pack_list = workspace.path().join("selected-packs.txt");
        let mut input = File::create(&pack_list)
            .map_err(|source| io_error(format!("create {}", pack_list.display()), source))?;
        for source in sources {
            let pack_name = format!("pack-{}.pack", source.canonical_id);
            writeln!(input, "{pack_name}")
                .map_err(|source| io_error(format!("write {}", pack_list.display()), source))?;
        }
        drop(input);
        let stdin = File::open(&pack_list)
            .map_err(|source| io_error(format!("open {}", pack_list.display()), source))?;
        let output_prefix = pack_dir.join("pack-crab-rollup");
        run_git(
            Command::new("git")
                .arg(format!("--git-dir={}", source_git.display()))
                .arg("pack-objects")
                .arg("--quiet")
                .arg("--stdin-packs")
                .arg("--reuse-delta")
                .arg("--reuse-object")
                .arg("--delta-base-offset")
                .arg("--depth=64")
                .arg(&output_prefix)
                .stdin(Stdio::from(stdin))
                .stdout(Stdio::null()),
            "consolidate selected Git packs",
        )?;
        pack_dir
    } else {
        let resolved_git = workspace.path().join("resolved.git");
        initialize_bare_repository(&resolved_git)?;
        install_delta_bases(&resolved_git, delta_bases)?;
        for source in sources {
            let stdin = File::open(&source.path)
                .map_err(|error| io_error(format!("open {}", source.path.display()), error))?;
            run_git(
                Command::new("git")
                    .arg(format!("--git-dir={}", resolved_git.display()))
                    .args(["index-pack", "--fix-thin", "--stdin"])
                    .stdin(Stdio::from(stdin))
                    .stdout(Stdio::null()),
                "resolve selected Git pack delta bases",
            )?;
        }
        let object_list = workspace.path().join("selected-objects.txt");
        let mut input = File::create(&object_list)
            .map_err(|source| io_error(format!("create {}", object_list.display()), source))?;
        for oid in &source_oids {
            writeln!(input, "{}", gix_hash::ObjectId::from(*oid))
                .map_err(|source| io_error(format!("write {}", object_list.display()), source))?;
        }
        drop(input);
        let stdin = File::open(&object_list)
            .map_err(|source| io_error(format!("open {}", object_list.display()), source))?;
        let resolved_pack_dir = resolved_git.join("objects/pack");
        let output_prefix = resolved_pack_dir.join("pack-crab-rollup");
        run_git(
            Command::new("git")
                .arg(format!("--git-dir={}", resolved_git.display()))
                .arg("pack-objects")
                .arg("--quiet")
                .arg("--reuse-delta")
                .arg("--reuse-object")
                .arg("--delta-base-offset")
                .arg("--depth=64")
                .arg(&output_prefix)
                .stdin(Stdio::from(stdin))
                .stdout(Stdio::null()),
            "consolidate resolved Git pack objects",
        )?;
        resolved_pack_dir
    };
    tracing::debug!(
        source_pack_count = sources.len(),
        elapsed_ms = pack_generation_started.elapsed().as_millis() as u64,
        "consolidated selected Git packs"
    );
    let pack_path = std::fs::read_dir(&generated_pack_dir)
        .map_err(|source| io_error(format!("read {}", generated_pack_dir.display()), source))?
        .filter_map(std::result::Result::ok)
        .map(|entry| entry.path())
        .find(|path| {
            path.file_name()
                .and_then(|name| name.to_str())
                .is_some_and(|name| {
                    name.starts_with("pack-crab-rollup-") && name.ends_with(".pack")
                })
        })
        .ok_or_else(|| RepackError::SourceIntegrity {
            pack_id: "geometric-repack".to_owned(),
            reason: "selected-pack consolidation produced no pack".to_owned(),
        })?;
    let generated_validation = match validation {
        ConsolidationValidation::Full => GeneratedPackValidation::Full,
        ConsolidationValidation::Committed | ConsolidationValidation::Response => {
            GeneratedPackValidation::Structural
        }
    };
    let generated = verified_generated_pack(pack_path, generated_validation, None, None)?;
    if matches!(
        validation,
        ConsolidationValidation::Full | ConsolidationValidation::Committed
    ) {
        let mut generated_locations = PackLocationIter::open(
            generated.index_path(),
            generated.reverse_index_path(),
            generated.pack_size,
        )?;
        let mut generated_oids = Vec::<[u8; 20]>::new();
        for location in &mut generated_locations {
            let location = location?;
            let oid =
                location
                    .oid
                    .as_bytes()
                    .try_into()
                    .map_err(|_| RepackError::SourceIntegrity {
                        pack_id: generated.pack_id.clone(),
                        reason: "consolidated pack contains a non-SHA1 object".to_owned(),
                    })?;
            generated_oids.push(oid);
        }
        generated_oids.sort_unstable();
        generated_oids.dedup();
        if generated_oids != source_oids {
            return Err(RepackError::SourceIntegrity {
                pack_id: generated.pack_id.clone(),
                reason: "consolidated pack does not preserve the selected object set".to_owned(),
            });
        }
    }
    Ok(GeometricRepackedRepository {
        _workspace: workspace,
        packs: vec![generated],
    })
}

/// Join a complete pack inventory without inflating or recompressing entries.
///
/// OFS_DELTA offsets are relative to the current entry, so shifting every
/// entry in one source pack by the same amount preserves those links. The
/// caller must prove that the committed source indexes exactly match its
/// selected object set; the receiving Git process validates the joined pack.
pub fn concatenate_complete_pack_inventory(
    sources: &[RepackSource],
) -> Result<ConcatenatedPack, RepackError> {
    concatenate_complete_pack_inventory_inner(sources, true)
}

fn concatenate_complete_pack_inventory_inner(
    sources: &[RepackSource],
    validate_sources: bool,
) -> Result<ConcatenatedPack, RepackError> {
    if sources.len() < 2 {
        return Err(RepackError::SourceIntegrity {
            pack_id: "complete-pack-concatenation".to_owned(),
            reason: "complete-pack concatenation requires at least two source packs".to_owned(),
        });
    }

    let workspace =
        tempfile::tempdir().map_err(|source| io_error("create concatenation workspace", source))?;
    let output_path = workspace.path().join("complete-pack-concatenated.pack");
    let mut output = File::create(&output_path)
        .map_err(|source| io_error("create concatenated pack", source))?;
    let mut source_ids = BTreeSet::new();
    let mut total_objects = 0_u64;
    for source in sources {
        if !source_ids.insert(source.canonical_id.as_str()) {
            return Err(RepackError::SourceIntegrity {
                pack_id: source.canonical_id.clone(),
                reason: "duplicate source pack id".to_owned(),
            });
        }
        if validate_sources {
            validate_source(source)?;
        }
        let mut input = File::open(&source.path)
            .map_err(|error| io_error(format!("open {}", source.path.display()), error))?;
        let mut header = [0_u8; 12];
        input
            .read_exact(&mut header)
            .map_err(|error| io_error(format!("read {} header", source.path.display()), error))?;
        let version =
            u32::from_be_bytes(header[4..8].try_into().map_err(|_| RepackError::Pack {
                source: PackError::InvalidPackFile {
                    path: source.path.clone(),
                    reason: "source pack header has an invalid version".to_owned(),
                },
            })?);
        if &header[..4] != b"PACK" || !matches!(version, 2 | 3) {
            return Err(RepackError::Pack {
                source: PackError::InvalidPackFile {
                    path: source.path.clone(),
                    reason: "source pack has an unsupported header".to_owned(),
                },
            });
        }
        let object_count = u64::from(u32::from_be_bytes(header[8..12].try_into().map_err(
            |_| RepackError::Pack {
                source: PackError::InvalidPackFile {
                    path: source.path.clone(),
                    reason: "source pack header has an invalid object count".to_owned(),
                },
            },
        )?));
        if object_count != source.object_count {
            return Err(RepackError::SourceIntegrity {
                pack_id: source.canonical_id.clone(),
                reason: format!(
                    "pack header has {object_count} objects but manifest records {}",
                    source.object_count
                ),
            });
        }
        total_objects = total_objects.checked_add(object_count).ok_or_else(|| {
            RepackError::SourceIntegrity {
                pack_id: source.canonical_id.clone(),
                reason: "concatenated pack object count overflows u32".to_owned(),
            }
        })?;
    }
    let total_objects_u32 =
        u32::try_from(total_objects).map_err(|_| RepackError::SourceIntegrity {
            pack_id: "complete-pack-concatenation".to_owned(),
            reason: "concatenated pack object count exceeds Git's pack limit".to_owned(),
        })?;
    let mut pack_header = [0_u8; 12];
    pack_header[..4].copy_from_slice(b"PACK");
    pack_header[4..8].copy_from_slice(&2_u32.to_be_bytes());
    pack_header[8..].copy_from_slice(&total_objects_u32.to_be_bytes());
    output
        .write_all(&pack_header)
        .map_err(|source| io_error("write concatenated pack header", source))?;

    let mut pack_sha1 = Sha1::new();
    pack_sha1.update(pack_header);
    let mut content_hasher = blake3::Hasher::new();
    content_hasher.update(&pack_header);
    let mut buffer = vec![0_u8; 1024 * 1024];
    for source in sources {
        let mut input = File::open(&source.path)
            .map_err(|error| io_error(format!("open {}", source.path.display()), error))?;
        let source_size = source.size;
        let body_size = source_size
            .checked_sub(32)
            .ok_or_else(|| RepackError::Pack {
                source: PackError::InvalidPackFile {
                    path: source.path.clone(),
                    reason: "source pack is too short for header and checksum".to_owned(),
                },
            })?;
        input
            .seek(std::io::SeekFrom::Start(12))
            .map_err(|error| io_error(format!("seek {} body", source.path.display()), error))?;
        let mut remaining = body_size;
        while remaining > 0 {
            let read_len = remaining.min(buffer.len() as u64) as usize;
            input
                .read_exact(&mut buffer[..read_len])
                .map_err(|error| io_error(format!("read {} body", source.path.display()), error))?;
            output
                .write_all(&buffer[..read_len])
                .map_err(|source| io_error("write concatenated pack body", source))?;
            pack_sha1.update(&buffer[..read_len]);
            content_hasher.update(&buffer[..read_len]);
            remaining -= read_len as u64;
        }
    }
    let checksum: [u8; 20] = pack_sha1.finalize().into();
    content_hasher.update(&checksum);
    output
        .write_all(&checksum)
        .and_then(|_| output.flush())
        .map_err(|source| io_error("finish concatenated pack", source))?;
    drop(output);

    let pack_hash = *content_hasher.finalize().as_bytes();
    let pack_size = std::fs::metadata(&output_path)
        .map_err(|source| io_error(format!("stat {}", output_path.display()), source))?
        .len();
    Ok(ConcatenatedPack {
        _workspace: workspace,
        pack_path: output_path,
        pack_id: blake3::Hash::from_bytes(pack_hash).to_hex().to_string(),
        pack_hash,
        pack_size,
        object_count: total_objects,
        git_sha1: checksum.iter().map(|byte| format!("{byte:02x}")).collect(),
    })
}

fn write_concatenated_pack_index(
    sources: &[RepackSource],
    index_path: &Path,
    pack_checksum: gix_hash::ObjectId,
) -> Result<(), RepackError> {
    let object_count = sources.iter().try_fold(0_u64, |total, source| {
        total
            .checked_add(source.object_count)
            .ok_or_else(|| RepackError::SourceIntegrity {
                pack_id: "complete-pack-concatenation".to_owned(),
                reason: "concatenated index object count overflow".to_owned(),
            })
    })?;
    let capacity = usize::try_from(object_count).map_err(|_| RepackError::SourceIntegrity {
        pack_id: "complete-pack-concatenation".to_owned(),
        reason: "concatenated index object count exceeds platform capacity".to_owned(),
    })?;
    let mut entries = Vec::with_capacity(capacity);
    let mut body_offset = 12_u64;
    for source in sources {
        let locations =
            PackLocationIter::open(&source.index_path, &source.reverse_index_path, source.size)?;
        for location in locations {
            let location = location?;
            let relative = location.pack_offset.checked_sub(12).ok_or_else(|| {
                RepackError::SourceIntegrity {
                    pack_id: source.canonical_id.clone(),
                    reason: "source object precedes its pack body".to_owned(),
                }
            })?;
            let offset =
                body_offset
                    .checked_add(relative)
                    .ok_or_else(|| RepackError::SourceIntegrity {
                        pack_id: source.canonical_id.clone(),
                        reason: "concatenated pack offset overflow".to_owned(),
                    })?;
            entries.push(PackIndexEntry {
                oid: location.oid,
                crc32: location.crc32,
                offset,
            });
        }
        let body_size =
            source
                .size
                .checked_sub(32)
                .ok_or_else(|| RepackError::SourceIntegrity {
                    pack_id: source.canonical_id.clone(),
                    reason: "source pack is too short for header and checksum".to_owned(),
                })?;
        body_offset =
            body_offset
                .checked_add(body_size)
                .ok_or_else(|| RepackError::SourceIntegrity {
                    pack_id: source.canonical_id.clone(),
                    reason: "concatenated pack length overflow".to_owned(),
                })?;
    }
    write_pack_index_v2(&mut entries, index_path, pack_checksum).map_err(RepackError::from)
}

struct InstalledSourcePack {
    index_path: PathBuf,
    oids: Vec<[u8; 20]>,
}

fn install_source_packs(
    pack_dir: &Path,
    sources: &[RepackSource],
    index_concurrency: usize,
    collect_oids: bool,
) -> Result<(Vec<[u8; 20]>, Vec<PathBuf>), RepackError> {
    if sources.is_empty() {
        return Ok((Vec::new(), Vec::new()));
    }
    let batch_size = index_concurrency.max(1).min(sources.len());
    let mut source_oids = Vec::new();
    let mut source_indexes = Vec::with_capacity(sources.len());
    for batch in sources.chunks(batch_size) {
        let results = std::thread::scope(|scope| {
            let handles = batch
                .iter()
                .map(|source| {
                    scope.spawn(move || install_source_pack(pack_dir, source, collect_oids))
                })
                .collect::<Vec<_>>();
            handles
                .into_iter()
                .map(|handle| handle.join())
                .collect::<Vec<_>>()
        });
        for (source, result) in batch.iter().zip(results) {
            let installed = match result {
                Ok(Ok(installed)) => installed,
                Ok(Err(error)) => return Err(error),
                Err(_) => {
                    return Err(RepackError::SourceIntegrity {
                        pack_id: source.canonical_id.clone(),
                        reason: "source pack installation worker panicked".to_owned(),
                    });
                }
            };
            source_oids.extend(installed.oids);
            source_indexes.push(installed.index_path);
        }
    }
    Ok((source_oids, source_indexes))
}

fn install_source_pack(
    pack_dir: &Path,
    source: &RepackSource,
    collect_oids: bool,
) -> Result<InstalledSourcePack, RepackError> {
    let installed = install_pack_files_from_paths_with_identity(
        pack_dir,
        &source.path,
        &source.index_path,
        &source.reverse_index_path,
        &source.canonical_id,
        source.size,
        source.object_count,
        source.verified_identity,
    )?;
    let oids =
        if collect_oids {
            let mut locations =
                PackLocationIter::open(&installed.idx_path, &installed.rev_path, source.size)?;
            let mut oids = Vec::new();
            for location in &mut locations {
                let location = location?;
                let oid = location.oid.as_bytes().try_into().map_err(|_| {
                    RepackError::SourceIntegrity {
                        pack_id: source.canonical_id.clone(),
                        reason: "selected pack contains a non-SHA1 object".to_owned(),
                    }
                })?;
                oids.push(oid);
            }
            oids
        } else {
            Vec::new()
        };
    Ok(InstalledSourcePack {
        index_path: installed.idx_path,
        oids,
    })
}

/// Generates one self-contained pack for an exact set of selected objects.
///
/// The source packs are validated before Git repacks them. The generated
/// index is compared with the requested set so Git cannot silently add a
/// filtered-out object as a delta base.
pub fn repack_selected_objects(
    sources: &[RepackSource],
    selected_oids: &[gix_hash::ObjectId],
) -> Result<GeometricRepackedRepository, RepackError> {
    if sources.is_empty() {
        return Err(RepackError::SelectedObjectSet {
            pack_id: "selected-pack".to_owned(),
            reason: "no source packs were supplied".to_owned(),
        });
    }
    let selected = normalize_selected_oids(selected_oids, "selected-pack")?;

    let workspace =
        tempfile::tempdir().map_err(|source| io_error("create selected-pack workspace", source))?;
    let source_git = workspace.path().join("source.git");
    initialize_bare_repository(&source_git)?;
    let pack_dir = source_git.join("objects/pack");
    let concurrency = std::thread::available_parallelism()
        .map_or(DEFAULT_REPACK_INDEX_CONCURRENCY, |parallelism| {
            parallelism.get().min(DEFAULT_REPACK_INDEX_CONCURRENCY)
        });
    let _ = install_source_packs(&pack_dir, sources, concurrency, false)?;

    let object_list = workspace.path().join("selected-objects.txt");
    let mut input = File::create(&object_list)
        .map_err(|source| io_error(format!("create {}", object_list.display()), source))?;
    for oid in &selected {
        writeln!(input, "{oid}")
            .map_err(|source| io_error(format!("write {}", object_list.display()), source))?;
    }
    drop(input);
    let generated = pack_selected_objects(
        &source_git,
        &pack_dir,
        &object_list,
        &selected,
        "pack-crab-selected",
        // Committed source packs were object-validated at publication. The
        // response still checks pack/index identity and the exact object set;
        // the receiving Git client validates object bodies with index-pack.
        GeneratedPackValidation::Structural,
    )?;
    Ok(GeometricRepackedRepository {
        _workspace: workspace,
        packs: vec![generated],
    })
}

/// Check whether source pack indexes contain each requested object exactly once.
///
/// Source body integrity remains the caller's responsibility because this
/// check reads only verified index sidecars, not packed entries.
pub fn source_pack_inventory_matches_object_ids(
    sources: &[RepackSource],
    selected_oids: &[gix_hash::ObjectId],
) -> Result<bool, RepackError> {
    let selected = normalize_selected_oids(selected_oids, "selected-pack")?;
    let source_oids = source_pack_inventory_object_ids(sources)?;
    Ok(source_oids == selected)
}

/// Check whether source pack indexes cover exactly the requested object set.
///
/// Repeated OIDs are allowed because separate packs in one Git object database
/// may contain the same object. A single response pack must instead use
/// [`source_pack_inventory_matches_object_ids`].
pub fn source_pack_inventory_covers_object_ids(
    sources: &[RepackSource],
    selected_oids: &[gix_hash::ObjectId],
) -> Result<bool, RepackError> {
    let selected = normalize_selected_oids(selected_oids, "selected-pack")?;
    let mut source_oids = source_pack_inventory_object_ids(sources)?;
    source_oids.dedup();
    Ok(source_oids == selected)
}

fn source_pack_inventory_object_ids(
    sources: &[RepackSource],
) -> Result<Vec<gix_hash::ObjectId>, RepackError> {
    let mut source_oids = Vec::new();
    for source in sources {
        let locations =
            PackLocationIter::open(&source.index_path, &source.reverse_index_path, source.size)?;
        if source.verified_identity.is_some_and(|identity| {
            locations.pack_checksum().as_bytes() != identity.git_sha1.as_slice()
        }) {
            return Err(RepackError::SourceIntegrity {
                pack_id: source.canonical_id.clone(),
                reason: "pack index checksum does not match the verified pack trailer".to_owned(),
            });
        }
        source_oids.extend(locations.sorted_object_ids());
    }
    source_oids.sort_unstable();
    Ok(source_oids)
}

/// Return REF_DELTA bases needed by native selected-pack consolidation.
///
/// Disjoint complete packs use Crab's byte-preserving concatenation path and
/// therefore need no materialized bases. When duplicate OIDs require native
/// Git to rewrite the selected object set, this scans only entry headers. All
/// bases are returned so thin-pack repair is independent of pack order.
pub fn selected_pack_ref_delta_base_ids(
    sources: &[RepackSource],
) -> Result<Vec<gix_hash::ObjectId>, RepackError> {
    let inventory = source_pack_inventory_object_ids(sources)?;
    if !inventory.windows(2).any(|pair| pair[0] == pair[1]) {
        return Ok(Vec::new());
    }
    let mut bases = BTreeSet::new();
    for source in sources {
        let reader = BufReader::new(
            File::open(&source.path)
                .map_err(|error| io_error(format!("open {}", source.path.display()), error))?,
        );
        let entries = gix_pack::data::input::BytesToEntriesIter::new_from_header(
            reader,
            gix_pack::data::input::Mode::Verify,
            gix_pack::data::input::EntryDataMode::Ignore,
            gix_hash::Kind::Sha1,
        )
        .map_err(|error| RepackError::SourceIntegrity {
            pack_id: source.canonical_id.clone(),
            reason: format!("cannot scan pack entry headers: {error}"),
        })?;
        for entry in entries {
            let entry = entry.map_err(|error| RepackError::SourceIntegrity {
                pack_id: source.canonical_id.clone(),
                reason: format!("cannot scan pack entry: {error}"),
            })?;
            if let gix_pack::data::entry::Header::RefDelta { base_id } = entry.header {
                bases.insert(base_id);
            }
        }
    }
    Ok(bases.into_iter().collect())
}

fn install_delta_bases(source_git: &Path, bases: &[RepackDeltaBase]) -> Result<(), RepackError> {
    let mut verified = BTreeMap::new();
    for base in bases {
        if crate::incoming_pack::object_id(base.kind, &base.data) != base.oid {
            return Err(RepackError::SourceIntegrity {
                pack_id: base.oid.to_string(),
                reason: "external delta base identity mismatch".to_owned(),
            });
        }
        if let Some(existing) = verified.insert(base.oid, (base.kind, base.data.as_slice()))
            && existing != (base.kind, base.data.as_slice())
        {
            return Err(RepackError::SourceIntegrity {
                pack_id: base.oid.to_string(),
                reason: "conflicting external delta bases".to_owned(),
            });
        }
    }
    for (oid, (kind, data)) in verified {
        let hex = oid.to_string();
        let object_dir = source_git.join("objects").join(&hex[..2]);
        std::fs::create_dir_all(&object_dir)
            .map_err(|error| io_error(format!("create {}", object_dir.display()), error))?;
        let object_path = object_dir.join(&hex[2..]);
        let file = File::options()
            .write(true)
            .create_new(true)
            .open(&object_path)
            .map_err(|error| io_error(format!("create {}", object_path.display()), error))?;
        let mut encoder = flate2::write::ZlibEncoder::new(file, flate2::Compression::fast());
        write!(encoder, "{} {}\0", kind, data.len())
            .and_then(|()| encoder.write_all(data))
            .map_err(|error| io_error(format!("write {}", object_path.display()), error))?;
        encoder
            .finish()
            .map_err(|error| io_error(format!("finish {}", object_path.display()), error))?;
    }
    Ok(())
}

/// Generate the exact self-contained pack for an existing shallow client's negotiation.
///
/// The source packs are one immutable repository inventory. Git evaluates the
/// requested wants and common haves with the client's shallow boundaries
/// installed, then the generated index is compared with that exact revision
/// selection so reused deltas cannot add an unauthorized object. Source packs
/// must have passed object validation before entering the committed inventory;
/// the generated transfer pack revalidates its pack, index, reverse-index, and
/// exact object-set checksums without inflating every object a second time.
pub fn repack_shallow_fetch(
    sources: &[RepackSource],
    wants: &[gix_hash::ObjectId],
    common_haves: &[gix_hash::ObjectId],
    shallow: &[gix_hash::ObjectId],
    included_tags: &[ShallowFetchTag],
    maximum_objects: usize,
) -> Result<GeometricRepackedRepository, RepackError> {
    if sources.is_empty() || wants.is_empty() || common_haves.is_empty() || shallow.is_empty() {
        return Err(RepackError::SelectedObjectSet {
            pack_id: "shallow-fetch".to_owned(),
            reason: "shallow fetch requires source packs, wants, common haves, and boundaries"
                .to_owned(),
        });
    }

    let workspace =
        tempfile::tempdir().map_err(|source| io_error("create shallow-fetch workspace", source))?;
    let source_git = workspace.path().join("source.git");
    initialize_bare_repository(&source_git)?;
    let pack_dir = source_git.join("objects/pack");
    let concurrency = std::thread::available_parallelism()
        .map_or(DEFAULT_REPACK_INDEX_CONCURRENCY, |parallelism| {
            parallelism.get().min(DEFAULT_REPACK_INDEX_CONCURRENCY)
        });
    let _ = install_source_packs(&pack_dir, sources, concurrency, false)?;

    let shallow_path = source_git.join("shallow");
    let mut shallow_file = File::create(&shallow_path)
        .map_err(|source| io_error(format!("create {}", shallow_path.display()), source))?;
    for oid in shallow {
        writeln!(shallow_file, "{oid}")
            .map_err(|source| io_error(format!("write {}", shallow_path.display()), source))?;
    }
    drop(shallow_file);

    let revisions_path = workspace.path().join("shallow-fetch-revisions.txt");
    let mut revisions = File::create(&revisions_path)
        .map_err(|source| io_error(format!("create {}", revisions_path.display()), source))?;
    for oid in wants {
        writeln!(revisions, "{oid}")
            .map_err(|source| io_error(format!("write {}", revisions_path.display()), source))?;
    }
    for oid in common_haves {
        writeln!(revisions, "^{oid}")
            .map_err(|source| io_error(format!("write {}", revisions_path.display()), source))?;
    }
    drop(revisions);

    let object_list = workspace.path().join("shallow-fetch-objects.txt");
    let revision_input = File::open(&revisions_path)
        .map_err(|source| io_error(format!("open {}", revisions_path.display()), source))?;
    let object_output = File::create(&object_list)
        .map_err(|source| io_error(format!("create {}", object_list.display()), source))?;
    run_git(
        Command::new("git")
            .arg(format!("--git-dir={}", source_git.display()))
            .args(["rev-list", "--stdin", "--objects", "--no-object-names"])
            .stdin(Stdio::from(revision_input))
            .stdout(Stdio::from(object_output)),
        "enumerate shallow fetch objects",
    )?;
    let selected = read_selected_oids(&object_list, maximum_objects, "shallow-fetch")?;
    let selected = include_reachable_tag_objects(
        &source_git,
        &object_list,
        selected,
        included_tags,
        maximum_objects,
    )?;
    let generated = pack_selected_objects(
        &source_git,
        &pack_dir,
        &object_list,
        &selected,
        "pack-crab-shallow",
        GeneratedPackValidation::Structural,
    )?;
    Ok(GeometricRepackedRepository {
        _workspace: workspace,
        packs: vec![generated],
    })
}

fn include_reachable_tag_objects(
    source_git: &Path,
    object_list: &Path,
    mut selected: Vec<gix_hash::ObjectId>,
    included_tags: &[ShallowFetchTag],
    maximum_objects: usize,
) -> Result<Vec<gix_hash::ObjectId>, RepackError> {
    let selected_set = selected.iter().copied().collect::<BTreeSet<_>>();
    let included_tags = included_tags
        .iter()
        .filter(|tag| tag.target != tag.peeled && selected_set.contains(&tag.peeled))
        .collect::<Vec<_>>();
    if included_tags.is_empty() {
        return Ok(selected);
    }

    let workspace = object_list
        .parent()
        .ok_or_else(|| RepackError::SelectedObjectSet {
            pack_id: "shallow-fetch".to_owned(),
            reason: "shallow fetch object list has no parent directory".to_owned(),
        })?;
    let revisions_path = workspace.join("shallow-fetch-tag-revisions.txt");
    let mut revisions = File::create(&revisions_path)
        .map_err(|source| io_error(format!("create {}", revisions_path.display()), source))?;
    for tag in included_tags {
        writeln!(revisions, "{}\n^{}", tag.target, tag.peeled)
            .map_err(|source| io_error(format!("write {}", revisions_path.display()), source))?;
    }
    drop(revisions);

    let tag_objects_path = workspace.join("shallow-fetch-tag-objects.txt");
    let revision_input = File::open(&revisions_path)
        .map_err(|source| io_error(format!("open {}", revisions_path.display()), source))?;
    let object_output = File::create(&tag_objects_path)
        .map_err(|source| io_error(format!("create {}", tag_objects_path.display()), source))?;
    run_git(
        Command::new("git")
            .arg(format!("--git-dir={}", source_git.display()))
            .args(["rev-list", "--stdin", "--objects", "--no-object-names"])
            .stdin(Stdio::from(revision_input))
            .stdout(Stdio::from(object_output)),
        "enumerate shallow fetch tag objects",
    )?;
    let remaining = maximum_objects.saturating_sub(selected.len());
    let tag_objects = read_selected_oids(&tag_objects_path, remaining, "shallow-fetch-tags")?;
    let mut selected_set = selected_set;
    let mut object_list = std::fs::OpenOptions::new()
        .append(true)
        .open(object_list)
        .map_err(|source| io_error("open shallow fetch object list for tags", source))?;
    for oid in tag_objects {
        if selected_set.insert(oid) {
            writeln!(object_list, "{oid}")
                .map_err(|source| io_error("append shallow fetch tag object", source))?;
            selected.push(oid);
        }
    }
    normalize_selected_oids(&selected, "shallow-fetch")
}

fn normalize_selected_oids(
    selected_oids: &[gix_hash::ObjectId],
    pack_id: &str,
) -> Result<Vec<gix_hash::ObjectId>, RepackError> {
    let mut selected = selected_oids.to_vec();
    if selected.is_empty()
        || selected
            .iter()
            .any(|oid| oid.as_bytes().len() != std::mem::size_of::<[u8; 20]>())
    {
        return Err(RepackError::SelectedObjectSet {
            pack_id: pack_id.to_owned(),
            reason: "selected object IDs must be non-empty SHA-1 IDs".to_owned(),
        });
    }
    selected.sort_unstable();
    if selected.windows(2).any(|pair| pair[0] == pair[1]) {
        return Err(RepackError::SelectedObjectSet {
            pack_id: pack_id.to_owned(),
            reason: "selected object IDs must be unique".to_owned(),
        });
    }
    Ok(selected)
}

fn read_selected_oids(
    path: &Path,
    maximum_objects: usize,
    pack_id: &str,
) -> Result<Vec<gix_hash::ObjectId>, RepackError> {
    let file =
        File::open(path).map_err(|source| io_error(format!("open {}", path.display()), source))?;
    let mut selected = Vec::new();
    for line in BufReader::new(file).lines() {
        if selected.len() >= maximum_objects {
            return Err(RepackError::SelectedObjectSet {
                pack_id: pack_id.to_owned(),
                reason: format!("selected object count exceeds {maximum_objects}"),
            });
        }
        let line = line.map_err(|source| io_error(format!("read {}", path.display()), source))?;
        let oid = gix_hash::ObjectId::from_hex(line.as_bytes()).map_err(|error| {
            RepackError::SelectedObjectSet {
                pack_id: pack_id.to_owned(),
                reason: format!("Git returned an invalid object ID: {error}"),
            }
        })?;
        selected.push(oid);
    }
    normalize_selected_oids(&selected, pack_id)
}

fn pack_selected_objects(
    source_git: &Path,
    pack_dir: &Path,
    object_list: &Path,
    selected: &[gix_hash::ObjectId],
    output_name: &str,
    validation: GeneratedPackValidation,
) -> Result<GeometricRepackedPack, RepackError> {
    let stdin = File::open(object_list)
        .map_err(|source| io_error(format!("open {}", object_list.display()), source))?;
    let output_prefix = pack_dir.join(output_name);
    run_git(
        Command::new("git")
            .arg(format!("--git-dir={}", source_git.display()))
            .arg("pack-objects")
            .arg("--quiet")
            .arg("--reuse-delta")
            .arg("--reuse-object")
            .arg("--delta-base-offset")
            // Git's automatic thread count multiplies delta-window memory;
            // cap each shared response producer without changing maintenance geometry.
            .arg(format!("--threads={RESPONSE_PACK_THREADS}"))
            .arg("--depth=64")
            .arg(&output_prefix)
            .stdin(Stdio::from(stdin))
            .stdout(Stdio::null()),
        "pack selected Git objects",
    )?;
    let output_prefix_name = format!("{output_name}-");
    let pack_path = std::fs::read_dir(pack_dir)
        .map_err(|source| io_error(format!("read {}", pack_dir.display()), source))?
        .filter_map(std::result::Result::ok)
        .map(|entry| entry.path())
        .find(|path| {
            path.file_name()
                .and_then(|name| name.to_str())
                .is_some_and(|name| {
                    name.starts_with(&output_prefix_name) && name.ends_with(".pack")
                })
        })
        .ok_or_else(|| RepackError::SelectedObjectSet {
            pack_id: "selected-pack".to_owned(),
            reason: "selected-object packing produced no pack".to_owned(),
        })?;
    verified_generated_pack(pack_path, validation, Some(selected), None)
}

fn verified_generated_pack(
    pack_path: PathBuf,
    validation: GeneratedPackValidation,
    expected_object_ids: Option<&[gix_hash::ObjectId]>,
    verified_identity: Option<VerifiedPackIdentity>,
) -> Result<GeometricRepackedPack, RepackError> {
    let index_path = pack_path.with_extension("idx");
    let reverse_index_path = pack_path.with_extension("rev");
    if !reverse_index_path.is_file() {
        write_pack_reverse_index(&index_path, &reverse_index_path)?;
    }
    if !index_path.is_file() || !reverse_index_path.is_file() {
        return Err(RepackError::SourceIntegrity {
            pack_id: pack_path.display().to_string(),
            reason: "consolidated pack is missing an index or reverse index".to_owned(),
        });
    }
    let pack_size = std::fs::metadata(&pack_path)
        .map_err(|source| io_error(format!("stat {}", pack_path.display()), source))?
        .len();
    let locations = PackLocationIter::open(&index_path, &reverse_index_path, pack_size)?;
    let object_count = locations.object_count();
    let git_sha1 = locations.pack_checksum().to_string();
    let (pack_hash, hashed_size) = if let Some(identity) = verified_identity {
        if identity.git_sha1.as_ref() != locations.pack_checksum().as_bytes() {
            return Err(RepackError::SourceIntegrity {
                pack_id: pack_path.display().to_string(),
                reason: "verified generated pack identity does not match its index checksum"
                    .to_owned(),
            });
        }
        (identity.content_hash, pack_size)
    } else {
        let (trailer, pack_hash, hashed_size) = verify_and_hash_pack_file(&pack_path)?;
        if trailer != git_sha1 {
            return Err(RepackError::SourceIntegrity {
                pack_id: pack_path.display().to_string(),
                reason: "generated pack index checksum does not match its pack trailer".to_owned(),
            });
        }
        (pack_hash, hashed_size)
    };
    if matches!(validation, GeneratedPackValidation::Full) {
        run_git(
            Command::new("git")
                .arg("verify-pack")
                .arg("-v")
                .arg(&index_path)
                .stdout(Stdio::null()),
            "verify consolidated Git pack",
        )?;
    }
    if hashed_size != pack_size {
        return Err(RepackError::SourceIntegrity {
            pack_id: pack_path.display().to_string(),
            reason: "consolidated pack changed during validation".to_owned(),
        });
    }
    let (index_hash, index_size) = hash_file(&index_path)?;
    let (reverse_index_hash, reverse_index_size) = hash_file(&reverse_index_path)?;
    let pack_id = blake3::Hash::from_bytes(pack_hash).to_hex().to_string();
    if let Some(expected_object_ids) = expected_object_ids {
        // Git v2 indexes store OIDs in lexicographic order. PackLocationIter::open
        // has already validated the index and reverse-index as one pair, so this
        // avoids allocating and sorting every generated OID a second time.
        if !locations.matches_sorted_object_ids(expected_object_ids) {
            return Err(RepackError::SelectedObjectSet {
                pack_id,
                reason: format!(
                    "generated {} objects for {} requested objects",
                    locations.object_count(),
                    expected_object_ids.len()
                ),
            });
        }
    }
    Ok(GeometricRepackedPack {
        pack_path,
        index_path,
        reverse_index_path,
        pack_id,
        pack_hash,
        pack_size,
        index_hash,
        index_size,
        reverse_index_hash,
        reverse_index_size,
        object_count,
        git_sha1,
        is_new: true,
    })
}

fn validate_source(source: &RepackSource) -> Result<(), RepackError> {
    let size = std::fs::metadata(&source.path)
        .map_err(|error| io_error(format!("metadata {}", source.path.display()), error))?
        .len();
    let hash = match source.verified_identity {
        Some(identity) => identity.content_hash,
        None => verify_and_hash_pack_file(&source.path)?.1,
    };
    if size != source.size {
        return Err(RepackError::SourceIntegrity {
            pack_id: source.canonical_id.clone(),
            reason: format!(
                "download has {size} bytes but manifest records {}",
                source.size
            ),
        });
    }
    let actual = blake3::Hash::from_bytes(hash).to_hex().to_string();
    if actual != source.canonical_id {
        return Err(RepackError::SourceIntegrity {
            pack_id: source.canonical_id.clone(),
            reason: format!("Blake3 identifier is {actual}"),
        });
    }
    Ok(())
}

fn validate_replacement_packs(
    workspace: &Path,
    refs: &BTreeSet<String>,
    packs: &[(&Path, &Path, &Path)],
) -> Result<(), RepackError> {
    let repository = workspace.join("validation.git");
    initialize_bare_repository(&repository)?;
    let pack_dir = repository.join("objects/pack");
    for (index, (pack_path, index_path, reverse_index_path)) in packs.iter().enumerate() {
        let prefix = format!("pack-replacement-{index}");
        for (source, target) in [
            (*pack_path, pack_dir.join(format!("{prefix}.pack"))),
            (*index_path, pack_dir.join(format!("{prefix}.idx"))),
            (*reverse_index_path, pack_dir.join(format!("{prefix}.rev"))),
        ] {
            std::fs::copy(source, &target)
                .map_err(|error| io_error(format!("copy {}", source.display()), error))?;
        }
    }
    pin_refs_and_fsck(&repository, refs, "validate replacement repository")
}

fn pin_refs_and_fsck(
    repository: &Path,
    refs: &BTreeSet<String>,
    operation: &'static str,
) -> Result<(), RepackError> {
    for (index, oid) in refs.iter().enumerate() {
        let name = format!("refs/heads/crab-repack-{index}");
        run_git(
            Command::new("git")
                .arg(format!("--git-dir={}", repository.display()))
                .arg("update-ref")
                .arg(&name)
                .arg(oid),
            operation,
        )?;
        if index == 0 {
            run_git(
                Command::new("git")
                    .arg(format!("--git-dir={}", repository.display()))
                    .arg("symbolic-ref")
                    .arg("HEAD")
                    .arg(&name),
                operation,
            )?;
        }
    }
    run_git(
        Command::new("git")
            .arg(format!("--git-dir={}", repository.display()))
            .arg("fsck")
            .arg("--strict")
            .arg("--full")
            .arg("--no-reflogs"),
        operation,
    )
}

fn initialize_bare_repository(path: &Path) -> Result<(), RepackError> {
    run_git(
        Command::new("git")
            .arg("init")
            .arg("--bare")
            .arg("--quiet")
            .arg(path),
        "initialize temporary bare repository",
    )
}

fn run_git(command: &mut Command, operation: &'static str) -> Result<(), RepackError> {
    // Every repack subprocess targets an explicit temporary repository or pack.
    // Local repository overrides could redirect object reads or replace the
    // installed shallow boundary, invalidating the pinned-inventory proof.
    for variable in [
        "GIT_ALTERNATE_OBJECT_DIRECTORIES",
        "GIT_CONFIG",
        "GIT_CONFIG_PARAMETERS",
        "GIT_CONFIG_COUNT",
        "GIT_OBJECT_DIRECTORY",
        "GIT_DIR",
        "GIT_WORK_TREE",
        "GIT_IMPLICIT_WORK_TREE",
        "GIT_GRAFT_FILE",
        "GIT_INDEX_FILE",
        "GIT_NO_REPLACE_OBJECTS",
        "GIT_REPLACE_REF_BASE",
        "GIT_PREFIX",
        "GIT_SHALLOW_FILE",
        "GIT_COMMON_DIR",
        "GIT_NAMESPACE",
    ] {
        command.env_remove(variable);
    }
    let status = command
        .status()
        .map_err(|source| io_error(format!("run {operation}"), source))?;
    if status.success() {
        Ok(())
    } else {
        Err(RepackError::Git { operation, status })
    }
}

fn hash_file(path: &Path) -> Result<([u8; 32], u64), RepackError> {
    let mut file =
        File::open(path).map_err(|source| io_error(format!("open {}", path.display()), source))?;
    let size = file
        .metadata()
        .map_err(|source| io_error(format!("stat {}", path.display()), source))?
        .len();
    let mut hasher = blake3::Hasher::new();
    io::copy(&mut file, &mut hasher)
        .map_err(|source| io_error(format!("hash {}", path.display()), source))?;
    Ok((*hasher.finalize().as_bytes(), size))
}

fn io_error(context: impl Into<String>, source: io::Error) -> RepackError {
    RepackError::Io {
        context: context.into(),
        source,
    }
}

